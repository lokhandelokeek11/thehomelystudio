/**
 * Helper to build direct pre-filled WhatsApp enquiry link
 */
export const buildWhatsAppLink = (productTitle, selectedVariantName = null, price = null) => {
  const number = '918087995835';
  let message = `Hello! I am interested in purchasing "${productTitle}" from The Homely Studio.`;
  if (selectedVariantName) {
    message += `\nSelected Option: ${selectedVariantName}`;
  }
  if (price) {
    message += `\nPrice: ₹${price}`;
  }
  message += `\n\nCan you please share more details and customization options? Thank you!`;

  return `https://wa.me/${number}?text=${encodeURIComponent(message)}`;
};
